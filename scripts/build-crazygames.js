// Build the copy of the game you upload to CrazyGames.
//   npm run build:crazygames -- https://your-brickfall-server.example.com
// Copies public/ into dist/crazygames/ with a config.js that turns on the CrazyGames SDK and points
// the game at your server. Zip the contents of that folder and upload it as an HTML5 game.
// Your server must allow the CrazyGames origins: set CORS_ORIGINS=https://*.crazygames.com
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const apiBase = (process.argv[2] || process.env.API_BASE || '').replace(/\/+$/, '');
if (!/^https:\/\/[^/]+$/.test(apiBase)) {
  console.error('Give the public HTTPS address of your Brickfall server, e.g.\n  npm run build:crazygames -- https://play.example.com');
  process.exit(1);
}

const out = path.join(root, 'dist', 'crazygames');
fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(path.join(root, 'public'), out, { recursive: true, filter: (src) => path.basename(src) !== '404.html' });
fs.writeFileSync(path.join(out, 'config.js'), `// Generated by npm run build:crazygames\nwindow.BRICKFALL_CONFIG = ${JSON.stringify({ platform: 'crazygames', apiBase })};\n`);
console.log(`Built ${path.relative(root, out)} (server: ${apiBase}). Zip the folder's contents and upload them to CrazyGames.`);
